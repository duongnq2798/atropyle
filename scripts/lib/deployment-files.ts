// deployments/<name>.json → packages/sdk/src/deployments/<name>.ts (spec §5.1), and deployments/team.json → team.ts.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseTeam } from '../../packages/sdk/src/deployments/teams';
import { parseDeployment } from '../../packages/sdk/src/deployments/types';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const NAMES = ['local', 'xlayer'] as const;

export function renderModule(name: string): string {
  const file = `${ROOT}deployments/${name}.json`;
  const head = `// Generated by scripts/deployments-sync.ts from deployments/${name}.json. Do not edit.\n`;
  if (!existsSync(file)) return `${head}export const ${name}: unknown = null;\n`;
  const json = JSON.parse(readFileSync(file, 'utf8'));
  parseDeployment(json);
  return `${head}export const ${name}: unknown = ${JSON.stringify(json, null, 2)};\n`;
}

/**
 * The SDK keeps only the chain ids, addresses and roles of deployments/team.json: the description and the sources
 * stay in the file, out of the bundle.
 */
export function renderTeamModule(): string {
  const file = `${ROOT}deployments/team.json`;
  const head = '// Generated by scripts/deployments-sync.ts from deployments/team.json. Do not edit.\n';
  const parsed = existsSync(file) ? parseTeam(JSON.parse(readFileSync(file, 'utf8')), true) : { chains: {} };
  const chains = Object.fromEntries(
    Object.entries(parsed.chains).map(([name, c]) => [
      name,
      { chainId: c.chainId, members: c.members.map((m) => ({ address: m.address, role: m.role })) },
    ]),
  );
  return `${head}import type { TeamFile } from './teams';\n\nexport const team: TeamFile = ${JSON.stringify({ chains }, null, 2)};\n`;
}

/** Returns true when every module already matches its JSON. With check = false, rewrites the stale ones. */
export function syncDeployments(check: boolean): boolean {
  let clean = true;
  const modules: [string, () => string][] = [
    ...NAMES.map((name): [string, () => string] => [name, () => renderModule(name)]),
    ['team', renderTeamModule],
  ];
  for (const [name, render] of modules) {
    const out = `${ROOT}packages/sdk/src/deployments/${name}.ts`;
    const next = render();
    const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
    if (cur === next) continue;
    clean = false;
    if (!check) {
      mkdirSync(dirname(out), { recursive: true });
      writeFileSync(out, next);
    }
  }
  return clean;
}
