import { fileURLToPath } from 'node:url';
import { type Program, packInputs, stepBytes } from '@atropyle/circuits';
import { cpuAbi, getDeployment, OUT_FLAGS } from '@atropyle/sdk';
import { vectorBytes } from '@atropyle/sdk/verify';
import { type Address, bytesToHex, encodeFunctionData, type Hex, hexToBytes } from 'viem';
import { HERO_CASES, type HeroCase } from '../../src/home/hero-cases';
import { HERO_STATES } from '../../src/home/impl/hero-states';
import type { LaneVector, NetlistGeometry } from './netlist-layout';

export const HERO_CIRCUIT_FILE = fileURLToPath(new URL('../../src/home/hero-circuit.ts', import.meta.url));
export const ASK_CALLS_FILE = fileURLToPath(new URL('../../src/home/impl/ask-calls.ts', import.meta.url));

export interface HeroAsk {
  /** The three questions as the processor reads them, in HERO_CASES order: lane j of the lit wires. */
  vectors: LaneVector[];
  /** Every case of state and inputs: 2^(nState + nIn). */
  cases: number;
  /** The netlist's answer to each question: newState and outputs as step() returns them, and the release bit. */
  answer: Record<HeroCase, { next: Hex; out: Hex; release: boolean }>;
  /** Calldata of step(policyId, state, inputs) for each question. */
  ask: Record<HeroCase, Hex>;
  target: { chainId: number; cpu: Address; policyId: string };
  rpc: { rpcUrls: readonly string[]; quorumRpcUrls: readonly (readonly string[])[] };
}

/**
 * The hero's questions, answered by the netlist of this repository and encoded for the processor on X Layer
 * mainnet. The bytes are P9's (packages/sdk/src/verify/vectors.ts): state 1 byte, inputs 3 bytes, least
 * significant first. policyId, the CPU and the RPCs come from the SDK's deployment (deployments/xlayer.json).
 */
export function heroAsk(p: Program): HeroAsk {
  const d = getDeployment('xlayer');
  const vectors = HERO_CASES.map((c) => ({
    state: HERO_STATES[c].state.state,
    inputs: packInputs(HERO_STATES[c].inputs),
  }));
  const answer = {} as HeroAsk['answer'];
  const ask = {} as HeroAsk['ask'];
  HERO_CASES.forEach((c, j) => {
    const bytes = vectorBytes(vectors[j]);
    const r = stepBytes(p, hexToBytes(bytes.state), hexToBytes(bytes.inputs));
    answer[c] = { next: bytesToHex(r.next), out: bytesToHex(r.out), release: (r.out[0] & OUT_FLAGS.release) !== 0 };
    ask[c] = encodeFunctionData({ abi: cpuAbi, functionName: 'step', args: [d.policyId, bytes.state, bytes.inputs] });
  });
  return {
    vectors,
    cases: 2 ** (p.nState + p.nIn),
    answer,
    ask,
    target: { chainId: d.chainId, cpu: d.cpu, policyId: d.policyId.toString() },
    rpc: { rpcUrls: d.rpcUrls, quorumRpcUrls: d.quorumRpcUrls },
  };
}

const HEADER = [
  '// Generated by apps/web/scripts/geometry.ts from the policy netlist (buildAll().program of @atropyle/circuits).',
  '// Do not edit: run `npm run geometry -w apps/web`. test/unit/hero-eval.test.ts fails when it is stale.',
];

/** Client code may import this one: a few numbers, no wire and no calldata. */
export function renderHeroCircuit(g: Pick<NetlistGeometry, 'nands' | 'latches' | 'depths'>, h: HeroAsk): string {
  return [
    ...HEADER,
    "/** What the hero's caption counts: NAND gates, latches, NAND layers, and every case of state and inputs. */",
    `export const CIRCUIT = { nands: ${g.nands}, latches: ${g.latches}, depths: ${g.depths}, cases: ${h.cases} } as const;`,
    "/** Whether the release output is 1 for each question of the hero: this page's answer, before X Layer's. */",
    `export const RELEASE = { ${HERO_CASES.map((c) => `${c}: ${h.answer[c].release}`).join(', ')} } as const;`,
    '',
  ].join('\n');
}

/** Only src/home/impl/ask.ts imports this one: the chunk "Ask X Layer" loads on intent. */
export function renderAskCalls(h: HeroAsk): string {
  const list = (a: readonly string[]) => `[${a.map((s) => `'${s}'`).join(', ')}]`;
  return [
    ...HEADER,
    "/** The processor and the policy on X Layer mainnet: getDeployment('xlayer'), from deployments/xlayer.json. */",
    `export const ASK_TARGET = { chainId: ${h.target.chainId}, cpu: '${h.target.cpu}', policyId: '${h.target.policyId}' } as const;`,
    '/** Its RPC operators as the deployment lists them; ask.ts asks the first URL of each group rpcPlan keeps. */',
    `export const ASK_RPC = { rpcUrls: ${list(h.rpc.rpcUrls)}, quorumRpcUrls: [${h.rpc.quorumRpcUrls.map(list).join(', ')}] } as const;`,
    '/** Calldata of step(policyId, state, inputs) for each question, encoded with viem when this file was generated. */',
    'export const ASK = {',
    ...HERO_CASES.map((c) => `  ${c}: '${h.ask[c]}',`),
    '} as const;',
    '/** What the netlist of this repository returns for each question: newState and outputs, and the release bit. */',
    'export const ANSWER = {',
    ...HERO_CASES.map(
      (c) => `  ${c}: { next: '${h.answer[c].next}', out: '${h.answer[c].out}', release: ${h.answer[c].release} },`,
    ),
    '} as const;',
    '',
  ].join('\n');
}
